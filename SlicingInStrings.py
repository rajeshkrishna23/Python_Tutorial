String1 = "HelloWorld"

# Syntax of Indexing in python String[Index].
# Syntax of Slicing in python  String[StartIndex:EndIndex:Step].
#Start -  Starting index of the string at which slicing operation starts .
#End - Ending index of the string at which slicing operation ends (excluded).
#Step - Integer that specifics the step for slicing.
print(String1[2:7:3])
